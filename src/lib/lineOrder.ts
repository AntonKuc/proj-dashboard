// Sorts line names for a project by their position in the source xlsx sheet.
// Lines with no known position (e.g. a project outside the source report,
// or a line added after the report was extracted) are appended alphabetically
// at the end, after all known lines.
export function sortLinesByExcelOrder(code: string, lines: string[]): string[] {
  const order = LINE_ORDER[code];
  if (!order) return [...lines].sort((a, b) => a.localeCompare(b));

  const index = new Map(order.map((line, i) => [line, i]));
  return [...lines].sort((a, b) => {
    const ia = index.has(a) ? index.get(a)! : Number.MAX_SAFE_INTEGER;
    const ib = index.has(b) ? index.get(b)! : Number.MAX_SAFE_INTEGER;
    if (ia !== ib) return ia - ib;
    return a.localeCompare(b);
  });
}

